    private void guardarCoche() {
        try {
            int numero = Integer.parseInt(matricula.getText());
            String nombre = fecha.getText();
            LocalDate fecha = LocalDate.parse(precio.getText());

            if (!ControlErrores.comprobarMatricula(nombre)) {
                mostrarError("Error: El nombre no puede estar vacío.");
                return;
            }
            if (!ControlErrores.comprobarPrecio(precio)) {
                mostrarError("Error: Los puntos deben estar entre 0 y 150000.");
                return;
            }
            if (!ControlErrores.comprobarMatriculacionFecha(fecha)) {
                mostrarError("Error: La fecha debe estar entre 1990 hasta la actualidad");
                return;
            }

            Coche nuevo = new Coche(matricula, fechaMatriculacion, precio);
            c.anadir(nuevo);

            mostrarCorrecto("Coche guardado");
            limpiar();

        } catch (NumberFormatException ex) {
            mostrarError("Error: Formato numérico incorrecto en número o puntos.");
        } catch (DateTimeParseException ex) {
            mostrarError("Error: Formato de fecha inválido (usa AAAA-MM-DD).");
        }
    }
    
